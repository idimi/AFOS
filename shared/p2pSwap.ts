/**
 * P2P Atomic Swap — Shared Types & State Machine
 *
 * Protocol:
 *   1. Agent A (taker) sends RFQ → Agent B (maker) receives agent_rfq
 *   2. Agent B accepts → sends p2p_quote_accepted to A (includes B's wallet addresses)
 *   3. Agent A initiates HTLC lock (signs tx) → sends p2p_htlc_params to B
 *      (includes: secretHash, A's lock tx hash, timelock values)
 *   4. Agent B verifies A's lock → initiates B's HTLC lock → sends p2p_htlc_locked to A
 *   5. Agent A verifies B's lock → reveals secret → sends p2p_swap_complete to B
 *   6. Agent B claims with secret → both sides record swap completion
 *
 * Timelock convention (HTLC safety):
 *   - A's timelock: 2 hours (longer — A locks first)
 *   - B's timelock: 1 hour  (shorter — B locks second, expires first)
 *   This ensures B cannot steal A's funds: if B doesn't lock, A's HTLC refunds after 2h.
 *   If A doesn't reveal, B's HTLC refunds after 1h.
 */

// ── Swap States ──────────────────────────────────────────────────────────────

export type P2PSwapState =
  | "idle"
  | "rfq_sent"           // A sent RFQ, waiting for B to accept
  | "rfq_received"       // B received RFQ, pending acceptance
  | "accepted"           // B accepted, waiting for A to lock HTLC
  | "htlc_initiating_a"  // A is signing/broadcasting HTLC lock tx
  | "htlc_locked_a"      // A's HTLC is on-chain, waiting for B to lock
  | "htlc_initiating_b"  // B is signing/broadcasting HTLC lock tx
  | "htlc_locked_both"   // Both HTLCs on-chain, A revealing secret
  | "settling"           // Secret revealed, B claiming
  | "complete"           // Swap settled on both chains
  | "failed"             // Unrecoverable error
  | "refunding"          // HTLC timelock expired, refunding
  | "refunded";          // Refund complete

// ── Signaling Message Types ──────────────────────────────────────────────────

export interface P2PQuoteAccepted {
  type: "p2p_quote_accepted";
  rfqId: string;
  fromPeerId: string;
  fromAlias?: string;
  /** B's wallet addresses for each chain (A needs these to build HTLC) */
  wallets: {
    solana?: string;
    ethereum?: string;
    bitcoin?: string;
  };
  /** B's agreed rate */
  rate: number;
  outAmount: number;
  timestamp: number;
}

export interface P2PHtlcParams {
  type: "p2p_htlc_params";
  rfqId: string;
  fromPeerId: string;
  /** SHA-256 hash of the secret (hex, no 0x prefix) — generated by A */
  secretHash: string;
  /** A's HTLC lock transaction hash (on A's chain) */
  lockTxHash: string;
  /** A's chain */
  lockChain: "solana" | "ethereum" | "bitcoin";
  /** A's HTLC escrow address / contract address */
  escrowAddress: string;
  /** Amount A locked */
  lockedAmount: number;
  lockedToken: string;
  /** Unix timestamp (seconds) when A's HTLC expires */
  timelockA: number;
  /** Unix timestamp (seconds) when B's HTLC should expire (must be < timelockA) */
  timelockB: number;
  timestamp: number;
}

export interface P2PHtlcLocked {
  type: "p2p_htlc_locked";
  rfqId: string;
  fromPeerId: string;
  /** B's HTLC lock transaction hash (on B's chain) */
  lockTxHash: string;
  /** B's chain */
  lockChain: "solana" | "ethereum" | "bitcoin";
  /** B's HTLC escrow address */
  escrowAddress: string;
  /** Amount B locked */
  lockedAmount: number;
  lockedToken: string;
  timestamp: number;
}

export interface P2PSwapComplete {
  type: "p2p_swap_complete";
  rfqId: string;
  fromPeerId: string;
  /** The preimage (secret) that unlocks B's HTLC */
  secret: string;
  /** A's claim/reveal transaction hash */
  revealTxHash?: string;
  timestamp: number;
}

export interface P2PSwapFailed {
  type: "p2p_swap_failed";
  rfqId: string;
  fromPeerId: string;
  reason: string;
  /** Whether the sender is initiating a refund */
  refunding?: boolean;
  timestamp: number;
}

export type P2PSignalingMessage =
  | P2PQuoteAccepted
  | P2PHtlcParams
  | P2PHtlcLocked
  | P2PSwapComplete
  | P2PSwapFailed;

// ── In-flight Swap Record ────────────────────────────────────────────────────

export interface InFlightSwap {
  rfqId: string;
  state: P2PSwapState;
  role: "taker" | "maker";  // taker = Agent A, maker = Agent B
  fromToken: string;
  toToken: string;
  fromChain: "solana" | "ethereum" | "bitcoin";
  toChain: "solana" | "ethereum" | "bitcoin";
  fromAmount: number;
  toAmount: number;
  rate: number;
  counterpartyPeerId: string;
  counterpartyAlias?: string;
  counterpartyWallets?: { solana?: string; ethereum?: string; bitcoin?: string };
  // HTLC params (set after A locks)
  secretHex?: string;         // only on taker side — NEVER share this until B locks
  secretHash?: string;        // shared with B
  timelockA?: number;         // A's HTLC expiry (Unix seconds)
  timelockB?: number;         // B's HTLC expiry (Unix seconds)
  lockTxHashA?: string;       // A's lock tx
  lockTxHashB?: string;       // B's lock tx
  escrowAddressA?: string;
  escrowAddressB?: string;
  revealTxHash?: string;
  startedAt: number;
  updatedAt: number;
  completedAt?: number;
  error?: string;
}

// ── HTLC Timelock Constants ──────────────────────────────────────────────────

/** Taker (A) HTLC timelock: 2 hours from now (seconds) */
export const HTLC_TIMELOCK_A_SECS = 2 * 60 * 60;

/** Maker (B) HTLC timelock: 1 hour from now (seconds) — must be < A's */
export const HTLC_TIMELOCK_B_SECS = 1 * 60 * 60;

/** How long to wait for counterparty to lock before giving up (ms) */
export const HTLC_LOCK_TIMEOUT_MS = 5 * 60 * 1000; // 5 minutes

// ── Helpers ──────────────────────────────────────────────────────────────────

/** Generate a cryptographically secure 32-byte secret and its SHA-256 hash */
export async function generateSwapSecret(): Promise<{ secretHex: string; secretHashHex: string }> {
  const secretBytes = crypto.getRandomValues(new Uint8Array(32));
  const secretHashBuf = await crypto.subtle.digest("SHA-256", secretBytes);
  const toHex = (buf: Uint8Array) => Array.from(buf).map(b => b.toString(16).padStart(2, "0")).join("");
  return {
    secretHex: toHex(secretBytes),
    secretHashHex: toHex(new Uint8Array(secretHashBuf)),
  };
}
